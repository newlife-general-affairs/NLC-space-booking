-- Role Enum
create type user_role as enum ('user', 'admin', 'system_admin');

-- User Roles Table
create table if not exists public.user_roles (
  id uuid references auth.users on delete cascade primary key,
  email text not null,
  role user_role not null default 'user',
  created_at timestamptz not null default now()
);

-- User Profiles Table
create table if not exists public.user_profiles (
  id uuid references auth.users on delete cascade primary key,
  full_name text,
  phone text,
  department text,
  updated_at timestamptz not null default now()
);

-- Announcements Table
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  created_by uuid references auth.users on delete set null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Room Issues Table
create table if not exists public.room_issues (
  id bigint generated by default as identity primary key,
  room_id bigint references public.rooms on delete cascade not null,
  reported_by uuid references auth.users on delete set null,
  description text not null,
  status text not null default 'pending', -- pending, investigating, resolved
  created_at timestamptz not null default now()
);

-- 新增 bookings 的存取密碼欄位 (隨機 8 位數)
alter table public.bookings add column if not exists access_code text;

-- Trigger to create user_roles and user_profiles on new signup
create or replace function public.handle_new_user() 
returns trigger as $$
begin
  insert into public.user_roles (id, email, role)
  values (new.id, new.email, 'user');
  
  insert into public.user_profiles (id)
  values (new.id);
  
  return new;
end;
$$ language plpgsql security definer;

-- Bind trigger (確保每次登入註冊時觸發)
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Enable RLS on new tables (後端使用 SERVICE_ROLE_KEY 會無視 RLS)
alter table public.user_roles enable row level security;
alter table public.user_profiles enable row level security;
alter table public.announcements enable row level security;
alter table public.room_issues enable row level security;
