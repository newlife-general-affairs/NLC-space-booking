-- 023_form_intake_log.sql
-- Google 表單自動匯入的稽核與去重紀錄。
-- 每一次成功收到的表單提交對應一列；form_response_id 唯一鍵用來擋 Apps Script 重送。

CREATE TABLE IF NOT EXISTS public.form_intake_log (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_response_id    TEXT        NOT NULL UNIQUE,
  received_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  borrower_name       TEXT,
  pastoral_zone       TEXT,
  phone               TEXT,
  form_type           TEXT,
  raw_payload         JSONB       NOT NULL,
  created_booking_ids BIGINT[]    NOT NULL DEFAULT '{}',
  needs_review        JSONB       NOT NULL DEFAULT '[]',
  skipped             JSONB       NOT NULL DEFAULT '[]',
  error               TEXT
);

COMMENT ON TABLE  public.form_intake_log                     IS 'Google 表單場地借用自動匯入紀錄（稽核 + 冪等）';
COMMENT ON COLUMN public.form_intake_log.form_response_id    IS 'Apps Script e.response.getId()，唯一，重送時據此回傳既有結果';
COMMENT ON COLUMN public.form_intake_log.raw_payload         IS 'Apps Script 送來的原始 JSON（含所有題目答案）';
COMMENT ON COLUMN public.form_intake_log.created_booking_ids IS '本次成功寫入的 bookings.id';
COMMENT ON COLUMN public.form_intake_log.needs_review        IS '有寫入但需人工確認的項目 [{bookingId, reason, raw}]';
COMMENT ON COLUMN public.form_intake_log.skipped             IS '完全無法解析、未寫入的項目 [{reason, raw}]';

CREATE INDEX IF NOT EXISTS idx_form_intake_log_received_at ON public.form_intake_log (received_at DESC);

ALTER TABLE public.form_intake_log ENABLE ROW LEVEL SECURITY;
-- 僅後端 service_role 存取；不建立任何 anon/authenticated 政策。
