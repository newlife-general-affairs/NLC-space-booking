-- rooms
CREATE TABLE IF NOT EXISTS public.rooms (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             TEXT    NOT NULL,
  capacity         INTEGER NOT NULL,
  description      TEXT,
  image_url        TEXT,
  branch           TEXT    DEFAULT '仁愛堂',
  polygon_points   TEXT,
  tuya_device_id   TEXT,
  tuya_light_id    TEXT,
  tuya_ac_id       TEXT,
  parent_room_id   BIGINT  REFERENCES public.rooms(id) ON DELETE SET NULL
);

